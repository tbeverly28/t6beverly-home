		<h3 class="attention-voice">Where to Start?</h3>
		<p class="quiet-voice">
			Players can choose from three difficulty levels when starting Devil
			May Cry: human, devil hunter, and nephilim. If you've played through
			any previous game in the series, the first two options are too easy.
			Nephilim offers a reasonable challenge without constantly pushing
			your skills to the limit. If you change your mind, you can always
			switch difficulty for any mission you've unlocked. Your first
			playthrough should be fun; plenty of post-game difficulty modes open
			up if you're looking for a more brutal experience.
