		<div class="text-wrapper">
			<p class="calm-voice one">
				<!-- ok I know this is a bad idea but I don't know pseudoelements that well yet -->
				I 've been a fan of the Devil May Cry series since its inception, and I
				don't care that Dante doesn't have white hair, or that his origin
				story has been retooled for this entry. I don't even care that he's
				fighting the demon king Mundus again; altering and revisiting key
				elementars are expected in any reboot. Regardless of how characters
				and events change, Ninja Theory stays faithful to the heart and soul
				of the series with this reimagining - and that's what matters.
			</p>
			<p class="calm-voice two">
				Stylish combat is the pillar supporting every other aspect in this incarnation of DMC. Wherever Dante goes or whatever new powers he gets, everything
				is foucsed on letting players tear through hordes of demons in
				entertaining ways. You start with Dante's signature sword and
				handguns, but your arsenal soon grows to rival previous titles in
				variety and complexity. By the end, you rapidly switch among weapons
				like a shotgun, axe, and scythe in order to keep the advancing enemies
				in check. The responsive, fast-paced battles require timing and
				precision, but cultivating those skills pays off. Strining together
				elaborate multi-weapon combos to hit an SSS rank is extremely
				gratifying.
			</p>
			<p class="calm-voice three">
				I’m impressed by the sheer variety of Dante’s moveset. Three guns, two angelic weapons, two demonic weapons, and one sword have unique abilities that you purchase. Because some moves are more useful than others (I still love the Stinger/Trillion Stabs combo), you can refund any spent points at no cost, encouraging you to experiment with the possibilities. Thankfully, you get the grappling powers for free, and they add mobility to the battlefield in ways that combine the concepts behind Nero’s Devil Bringer and Vergil’s teleportation from previous installments.
			</p>
			<p class="calm-voice four">
				As complicated as combat seems, it is surprisingly easy to control. Taking a page from its previous title, Heavenly Sword, Ninja Theory uses the shoulder buttons to shift between angelic and demonic weapons. I rarely found myself staying in one mode too long, opting instead to fire off a couple moves with one weapon before switching. One basic combo involves launching an enemy in the air from a distance (demon mode), then grappling and zooming toward it (angel mode), juggling it in the air with some scythe swings (angel), then slamming it to the ground to create an impact radius (demon). In practice, each move in that sequence only involves one trigger and one face button, resulting in rewarding (and visually stunning) displays of violence that you can direct with ease.
			</p>
			<p class="calm-voice five">
				When Dante isn’t fighting, he’s traversing a bizarre and breathtaking world. Despite the modern-day setting, most of DMC’s action takes place in Limbo, a dimension that exists parallel to reality. It sounds ridiculous, but this set-up serves as an excuse to put players in a surreal dreamscape where anything can happen. Streets break apart and crumble.
			</p>
		</div>
		
		<picture class="img-container two">
			<img src="https://www.gameuidatabase.com/uploads/DmC-Devil-May-Cry05182021-111112-72521_thumb.jpg" alt="" />
		</picture>

		<p class="calm-voice six">
			Gravity inverts. Buildings constrict. These visually amazing events aren’t relegated to cutscenes; the ground can change beneath your feet at any moment, which is a fantastic way to keep things interesting as players move from one fight to the next. Fortunately, the hints of platforming here are much better than previous entries in the series, so you can appreciate the curveballs the world throws at you without getting too frustrated.
		</p>
		<p class="calm-voice seven">
			I have a lot of praise to heap on DMC, but it doesn’t do everything right. With the exception of the final fight, the boss battles feel outdated. Instead of using the combat skills you’ve been honing, they mainly involve a brand of pattern recognition and dodging that would feel more at home in a 3D platformer. I was also disappointed by the implementation of the devil trigger ability. It’s useful, but it charges slowly and depletes quickly, giving it too small of a role in the combat experience. 
		</p>
		<p class="calm-voice eight">
			Lastly, the final levels don’t clear the high bar set by the early part of the game. Limbo becomes more predictable, and thanks to aggravating enemy combinations, combat involves far less imagination. It’s a shame, because these final missions should have been an opportunity to go all-out with combat and visuals. Instead, the game feels like it is running on fumes. Activate four generators and then align the symbols? Whatever you say, Vergil.
		</p>
		<p class="calm-voice nine">
			The last few missions aside, the mechanics, gameplay, and environments in Devil May Cry are exactly what I wanted. A reboot is a chance to revitalize a flagging series, and Ninja Theory has done that with a striking vision for the DMC universe and top-notch combat. Maybe this version of Devil May Cry will need rebooting in another 12 years, but for now, I can’t wait to see what’s next for Dante.
		</p>
